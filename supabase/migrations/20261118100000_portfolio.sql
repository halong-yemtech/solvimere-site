-- Team members' portfolios (/team/<slug> on the site), edited in Admin → Portfolio.
-- Replaces the Payload CMS (`payload` schema) that the separate portfolio app used:
-- data is copied over by portfolio/scripts/export-to-public.ts, then that app is removed.
--
-- Each profile and each list item is one JSON document (`data`), the same shape the CMS
-- stored. Images are referenced by portfolio_media id; files live in the public
-- `portfolio` Storage bucket.

-- ── tables ────────────────────────────────────────────────────────────────

create table if not exists public.portfolio_media (
  id bigint generated by default as identity primary key,
  path text not null unique,
  url text not null,
  alt text not null default '',
  filename text not null default '',
  mime_type text not null default '',
  filesize integer,
  width integer,
  height integer,
  created_at timestamptz not null default now()
);

create table if not exists public.portfolio_profiles (
  id bigint generated by default as identity primary key,
  -- The member's name in lowercase letters and digits: "Ha Long" → "halong".
  slug text not null unique check (slug ~ '^[a-z0-9]{1,60}$'),
  visibility text not null default 'private' check (visibility in ('public', 'private')),
  sort_order integer not null default 0,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.portfolio_items (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.portfolio_profiles (id) on delete cascade,
  kind text not null check (
    kind in (
      'services', 'pricing-plans', 'clients', 'testimonials', 'facts', 'statistics',
      'resume-entries', 'works', 'work-categories', 'blog-posts'
    )
  ),
  sort_order integer not null default 0,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create index if not exists portfolio_items_profile_kind on public.portfolio_items (profile_id, kind, sort_order);

-- Settings shared by every portfolio: sections shown, theme, maintenance mode.
create table if not exists public.portfolio_settings (
  id smallint primary key default 1 check (id = 1),
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

insert into public.portfolio_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.portfolio_guestbook (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  comment text not null check (char_length(comment) between 1 and 2000),
  approved boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists portfolio_guestbook_created on public.portfolio_guestbook (created_at desc);

-- ── updated_at ────────────────────────────────────────────────────────────

create or replace function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists touch_portfolio_profiles on public.portfolio_profiles;
create trigger touch_portfolio_profiles before update on public.portfolio_profiles
  for each row execute function private.touch_updated_at();

drop trigger if exists touch_portfolio_items on public.portfolio_items;
create trigger touch_portfolio_items before update on public.portfolio_items
  for each row execute function private.touch_updated_at();

drop trigger if exists touch_portfolio_settings on public.portfolio_settings;
create trigger touch_portfolio_settings before update on public.portfolio_settings
  for each row execute function private.touch_updated_at();

-- ── access ────────────────────────────────────────────────────────────────

alter table public.portfolio_media enable row level security;
alter table public.portfolio_profiles enable row level security;
alter table public.portfolio_items enable row level security;
alter table public.portfolio_settings enable row level security;
alter table public.portfolio_guestbook enable row level security;

grant select on public.portfolio_media, public.portfolio_profiles, public.portfolio_items,
  public.portfolio_settings, public.portfolio_guestbook to anon, authenticated;
grant insert on public.portfolio_guestbook to anon, authenticated;
grant insert, update, delete on public.portfolio_media, public.portfolio_profiles, public.portfolio_items,
  public.portfolio_guestbook to authenticated;
grant update on public.portfolio_settings to authenticated;

-- Visitors: public profiles and their items; staff: everything.
drop policy if exists "read public portfolios" on public.portfolio_profiles;
create policy "read public portfolios" on public.portfolio_profiles
  for select to anon, authenticated
  using (visibility = 'public' or private.is_staff());

drop policy if exists "staff manage portfolios" on public.portfolio_profiles;
create policy "staff manage portfolios" on public.portfolio_profiles
  for all to authenticated
  using (private.is_staff()) with check (private.is_staff());

drop policy if exists "read items of public portfolios" on public.portfolio_items;
create policy "read items of public portfolios" on public.portfolio_items
  for select to anon, authenticated
  using (
    private.is_staff()
    or exists (
      select 1 from public.portfolio_profiles p
      where p.id = profile_id and p.visibility = 'public'
    )
  );

drop policy if exists "staff manage portfolio items" on public.portfolio_items;
create policy "staff manage portfolio items" on public.portfolio_items
  for all to authenticated
  using (private.is_staff()) with check (private.is_staff());

drop policy if exists "read portfolio media" on public.portfolio_media;
create policy "read portfolio media" on public.portfolio_media
  for select to anon, authenticated using (true);

drop policy if exists "staff manage portfolio media" on public.portfolio_media;
create policy "staff manage portfolio media" on public.portfolio_media
  for all to authenticated
  using (private.is_staff()) with check (private.is_staff());

drop policy if exists "read portfolio settings" on public.portfolio_settings;
create policy "read portfolio settings" on public.portfolio_settings
  for select to anon, authenticated using (true);

drop policy if exists "staff update portfolio settings" on public.portfolio_settings;
create policy "staff update portfolio settings" on public.portfolio_settings
  for update to authenticated
  using (private.is_staff()) with check (private.is_staff());

-- Guest book: anyone can sign it (shown straight away); staff hide or delete.
drop policy if exists "read approved guestbook" on public.portfolio_guestbook;
create policy "read approved guestbook" on public.portfolio_guestbook
  for select to anon, authenticated
  using (approved or private.is_staff());

drop policy if exists "sign guestbook" on public.portfolio_guestbook;
create policy "sign guestbook" on public.portfolio_guestbook
  for insert to anon, authenticated
  with check (approved);

drop policy if exists "staff manage guestbook" on public.portfolio_guestbook;
create policy "staff manage guestbook" on public.portfolio_guestbook
  for all to authenticated
  using (private.is_staff()) with check (private.is_staff());

-- ── files ─────────────────────────────────────────────────────────────────

-- Portfolio files are public (they're shown on public pages); only staff can change them.
insert into storage.buckets (id, name, public)
values ('portfolio', 'portfolio', true)
on conflict (id) do update set public = true;

drop policy if exists "staff upload portfolio files" on storage.objects;
create policy "staff upload portfolio files" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'portfolio' and private.is_staff());

drop policy if exists "staff update portfolio files" on storage.objects;
create policy "staff update portfolio files" on storage.objects
  for update to authenticated
  using (bucket_id = 'portfolio' and private.is_staff())
  with check (bucket_id = 'portfolio' and private.is_staff());

drop policy if exists "staff delete portfolio files" on storage.objects;
create policy "staff delete portfolio files" on storage.objects
  for delete to authenticated
  using (bucket_id = 'portfolio' and private.is_staff());
